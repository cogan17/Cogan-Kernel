# Native KernelSU Next/BakaSU initrc integration. Sourced by report.sh.
# ksud owns the /metadata cache and its enable/disable/remove lifecycle.
CM_DEV=${CM_DEV:-/dev}
CM_KSUD=${CM_KSUD:-${CS_ADB:-/data/adb}/ksud}

init_update_pending() {
  cm_update=${CS_ADB:-/data/adb}/modules_update/cogan_smart
  [ -f "$cm_update/module.prop" ] &&
    [ "$(readlink -f "$MODROOT")" != "$(readlink -f "$cm_update")" ]
}

init_program() {
  # Only shell builtins: /data and third-party binaries are unavailable at these stages.
  cm_program='umask 077; want=$1; phase=$2; case "$want" in lz4|zstd) ;; *) exit 0;; esac; '
  cm_program=$cm_program'read -r a < /sys/kernel/cogan/abi; read -r d < /sys/kernel/cogan/device; read -r s < /sys/kernel/cogan/soc; read -r r < /sys/kernel/cogan/release; '
  cm_program=$cm_program'[ "$a" = 1 ] && [ "$d" = rothko ] && [ -n "$r" ] || exit 0; case "$s" in mt6989|MT6989|mediatek,mt6989|mediatek,MT6989) ;; *) exit 0;; esac; '
  cm_program=$cm_program'n=0; for z in /sys/block/zram*; do [ -r "$z/comp_algorithm" ] || continue; n=$((n+1)); av=; read -r av < "$z/comp_algorithm"; case " $av " in *" $want "*|*"[$want]"*) ;; *) printf "%s %s unsupported\n" "$want" "$phase" > /dev/.cogan_smart_zram_init; exit 0;; esac; done; '
  cm_program=$cm_program'result=matching; [ "$n" -gt 0 ] || result=missing; for z in /sys/block/zram*; do [ -r "$z/comp_algorithm" ] || continue; i=; read -r i < "$z/initstate"; if [ "$i" = 0 ]; then printf "%s\n" "$want" > "$z/comp_algorithm"; fi; av=; read -r av < "$z/comp_algorithm"; case "$av" in "$want"|*"[$want]"*) ;; *) result=pending;; esac; done; '
  cm_program=$cm_program'printf "%s %s %s\n" "$want" "$phase" "$result" > /dev/.cogan_smart_zram_init'
  printf '%s' "$cm_program"
}

sync_init() {
  cm_rc=$MODROOT/initrc/cogan-zram.rc
  : > "$CM_DATA/init.error"
  if init_update_pending; then
    printf '%s\n' error > "$CM_DATA/init.state"
    printf '%s\n' 'Pembaruan modul menunggu reboot. Selesaikan reboot pembaruan sebelum menyimpan pilihan boot.' > "$CM_DATA/init.error"
    return 1
  fi
  cm_probe_limit=3; cm_refresh_limit=5
  # Refresh and rollback must fit inside the root manager's 10-second boot stage.
  if [ "$1" = boot ]; then cm_probe_limit=1; cm_refresh_limit=2; fi
  if [ -f "$MODROOT/system.prop" ]; then
    cm_properties=$(cat "$MODROOT/system.prop")
    case "$cm_properties" in mmd.zram.comp_algorithm=lz4|mmd.zram.comp_algorithm=zstd) ;;
      *) printf '%s\n' error > "$CM_DATA/init.state"; printf '%s\n' 'system.prop memiliki isi lain; tidak ditimpa.' > "$CM_DATA/init.error"; return 1 ;; esac
  fi
  if [ -f "$cm_rc" ] && [ "$(read_node "$cm_rc")" != '# Generated by Cogan Smart. Change the selection in Manager.' ]; then
    printf '%s\n' error > "$CM_DATA/init.state"
    printf '%s\n' 'initrc memiliki isi lain; tidak ditimpa.' > "$CM_DATA/init.error"
    return 1
  fi
  cm_want=
  if [ "$BOOT" = 1 ] && [ "$RAM" != default ] && gate; then cm_want=$(compressor); fi
  cm_native=0; cm_had=0; [ ! -f "$cm_rc" ] || cm_had=1
  if { [ -n "$cm_want" ] || [ "$cm_had" = 1 ]; } &&
     [ -x "$CM_KSUD" ] && command -v timeout >/dev/null 2>&1 &&
     cm_help=$(timeout "$cm_probe_limit" "$CM_KSUD" initrc --help 2>/dev/null) &&
     printf '%s' "$cm_help" | grep -q refresh; then cm_native=1; fi
  cm_context=$(id -Z 2>/dev/null)
  case "$cm_context" in u:r:ksu:s0|u:r:su:s0) ;; *) cm_native=0 ;; esac
  if [ "$cm_native" = 0 ] && [ "$cm_had" = 1 ]; then
    printf '%s\n' error > "$CM_DATA/init.state"
    printf '%s\n' 'Root manager tidak dapat menyegarkan initrc lama.' > "$CM_DATA/init.error"
    return 1
  fi
  if [ "$cm_native" = 1 ]; then
    if [ "$cm_had" = 1 ]; then cp "$cm_rc" "$CM_DATA/init.previous" || return 1
    else rm -f "$CM_DATA/init.previous"; fi
    if [ -n "$cm_want" ]; then
      mkdir -p "$MODROOT/initrc" || return 1
      # One unquoted init token: init's tokenizer has no escapes inside "...", but outside quotes
      # \\ \" and "\ " stay literal. init expands exec arguments twice, so each $ becomes $$$$.
      cm_escaped=$(init_program | sed 's/\\/\\\\/g; s/"/\\"/g; s/ /\\ /g; s/\$/$$$$/g')
      {
        printf '# Generated by Cogan Smart. Change the selection in Manager.\n'
        # rothko: vendor init writes lz4 on post-fs-data, then system_ext starts system_perf_init on
        # load-bpf-programs, which initializes ZRAM. Module rc is parsed before system_ext, so the
        # load-bpf-programs run lands between the two.
        for cm_phase in init early-fs post-fs load-bpf-programs; do
          printf '\non %s && property:ro.product.device=rothko && property:ro.board.platform=mt6989\n' "$cm_phase"
          printf '    exec %s root root -- /system/bin/sh -c %s cogan-zram %s %s\n' "$cm_context" "$cm_escaped" "$cm_want" "$cm_phase"
        done
      } > "$cm_rc.tmp" && chmod 600 "$cm_rc.tmp" && mv "$cm_rc.tmp" "$cm_rc" || return 1
    else rm -f "$cm_rc"; fi
    # During installation, ksud refreshes the new modules_update entry after customize.sh.
    cm_changed=1
    if [ "$cm_had" = 1 ] && cmp -s "$cm_rc" "$CM_DATA/init.previous"; then cm_changed=0; fi
    if [ "$cm_had" = 0 ] && [ -z "$cm_want" ]; then cm_changed=0; fi
    if [ "$cm_changed" = 1 ] && [ "$1" != prepare ] && ! timeout "$cm_refresh_limit" "$CM_KSUD" initrc refresh > "$CM_DATA/init.error" 2>&1; then
      if [ "$cm_had" = 1 ]; then cp "$CM_DATA/init.previous" "$cm_rc"; else rm -f "$cm_rc"; fi
      # Roll back the manager's atomic cache too; retain the original error for diagnosis.
      timeout "$cm_refresh_limit" "$CM_KSUD" initrc refresh >/dev/null 2>&1 || :
      printf '%s\n' error > "$CM_DATA/init.state"
      return 1
    fi
    rm -f "$CM_DATA/init.previous"
    : > "$CM_DATA/init.error"
  fi
  # Native Android mmd reads this at setup. Do not enable mmd or change its size/writeback policy.
  cm_mmd=0
  case "$(getprop mmd.zram.enabled 2>/dev/null)" in true|1|y|yes|on) cm_mmd=1 ;; esac
  if [ -n "$cm_want" ] && [ "$cm_mmd" = 1 ]; then
    printf 'mmd.zram.comp_algorithm=%s\n' "$cm_want" > "$MODROOT/system.prop.tmp" &&
      mv "$MODROOT/system.prop.tmp" "$MODROOT/system.prop" || return 1
    cm_state=mmd
  else rm -f "$MODROOT/system.prop"; cm_state=unsupported; fi
  [ "$cm_native" = 0 ] || cm_state=ready
  [ -n "$cm_want" ] || cm_state=off
  printf '%s\n' "$cm_state" > "$CM_DATA/init.state"
}
